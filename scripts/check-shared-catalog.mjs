import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { PGlite } from "@electric-sql/pglite";
const db = new PGlite();
const id = (n) => `00000000-0000-0000-0000-${String(n).padStart(12, "0")}`;
const sql = (s) => db.exec(s);
const count = async (table) => Number((await db.query(`select count(*) as n from ${table}`)).rows[0].n);
await sql(`create schema auth; create role authenticated;
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  create table accounts(id uuid primary key);
  create table stores(id uuid primary key, account_id uuid references accounts, active boolean default true);
  create table test_access(user_id uuid, store_id uuid, operate boolean default true);
  create function has_store_access(s uuid) returns boolean language sql stable security definer as $$ select exists(select 1 from test_access where user_id=auth.uid() and store_id=s) $$;
  create function can_operate_store(s uuid) returns boolean language sql stable security definer as $$ select exists(select 1 from test_access where user_id=auth.uid() and store_id=s and operate) $$;
  create function can_manage_store(s uuid) returns boolean language sql stable security definer as $$ select can_operate_store(s) $$;`);
let schema = await readFile(new URL("../Lava Rapidos/supabase/schema.sql", import.meta.url), "utf8");
schema = schema.slice(0, schema.indexOf("-- VIEWS DE APOIO")).replace('create extension if not exists "uuid-ossp";', "").replaceAll("uuid_generate_v4()", "gen_random_uuid()");
await sql(schema);
for (const table of ["clientes", "carros", "parceiros", "atendimentos", "financeiro"]) {
  await sql(`alter table ${table} add store_id uuid references stores;
    alter table ${table} enable row level security;
    create policy origin_select on ${table} for select to authenticated using(has_store_access(store_id));
    create policy origin_insert on ${table} for insert to authenticated with check(can_operate_store(store_id));
    create policy origin_update on ${table} for update to authenticated using(can_operate_store(store_id)) with check(can_operate_store(store_id));`);
}
await sql(`alter table atendimentos add itens_servicos jsonb default '[]', add desconto numeric default 0;
  insert into accounts values ('${id(1)}'),('${id(2)}');
  insert into stores values ('${id(11)}','${id(1)}',true),('${id(12)}','${id(1)}',true),('${id(21)}','${id(2)}',true);
  insert into test_access values ('${id(101)}','${id(11)}',true),('${id(102)}','${id(12)}',true),('${id(103)}','${id(21)}',true);
  insert into clientes(id,store_id,nome) values ('${id(201)}','${id(11)}','Cliente A'),('${id(202)}','${id(21)}','Cliente externo');
  insert into carros(id,store_id,cliente_id,placa) values ('${id(301)}','${id(11)}','${id(201)}','ABC1D23');
  insert into parceiros(id,store_id,nome) values ('${id(401)}','${id(11)}','Parceiro A');
  grant usage on schema public,auth to authenticated;
  grant select,insert,update,delete on all tables in schema public to authenticated;`);
const migration = await readFile(new URL("../supabase/nexwash_shared_catalog.sql", import.meta.url), "utf8");
await sql(migration);
await sql(migration); // Reaplicação não modifica a opção já escolhida.
const asUser = (n) => sql(`reset role; select set_config('request.jwt.claim.sub','${id(n)}',false); set role authenticated;`);
await asUser(102);
assert.equal(await count("carros"), 1, "Carro da loja A visível na loja B");
assert.equal(await count("parceiros"), 1);
assert.equal(await count("clientes"), 1, "Cliente vinculado visível, outra conta isolada");
assert.equal((await db.query(`select * from list_legacy_customers(array['${id(12)}']::uuid[])`)).rows.length, 1);
const create = (store, payload) => db.query("select create_legacy_atendimento($1, $2::jsonb) as id", [id(store), JSON.stringify(payload)]);
await create(12, { tipo: "PARTICULAR", cliente_id: id(201), carro_id: id(301), valor: 90, status_pg: "PAGO", forma_pgto: "PIX" });
await create(12, { tipo: "PARCEIRO", parceiro_id: id(401), valor: 100, status_pg: "PENDENTE" });
assert.equal(await count("atendimentos"), 2);
assert.equal(await count("financeiro"), 1, "Só a OS paga gera entrada");
assert.equal((await db.query("select count(distinct os_numero) as n from atendimentos")).rows[0].n, 2);
await assert.rejects(() => create(12, { tipo: "PARTICULAR", cliente_id: id(202), carro_id: id(301), valor: 1 }), /Cliente|Veículo/);
await assert.rejects(() => create(11, { tipo: "PARCEIRO", parceiro_id: id(401), valor: 1 }), /permissão/);
await asUser(103);
assert.equal(await count("carros"), 0, "Outra conta não pode ver carro compartilhado");
assert.equal(await count("parceiros"), 0);
assert.equal(await count("atendimentos"), 0);
await assert.rejects(() => create(21, { tipo: "PARCEIRO", parceiro_id: id(401), valor: 1 }), /Parceiro/);
