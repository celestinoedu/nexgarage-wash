await assert.rejects(() => create(12, { tipo: "PARCEIRO", parceiro_id: id(401), valor: 1 }), /Parceiro/);
await asUser(101);
await sql(`insert into parceiros(store_id,nome) values('${id(11)}','Novo parceiro');`);
assert.equal((await db.query("select show_all_stores from parceiros where nome='Novo parceiro'")).rows[0].show_all_stores, true);
await sql("reset role;");
await sql(migration);
assert.equal((await db.query(`select show_all_stores from parceiros where id='${id(401)}'`)).rows[0].show_all_stores, false);
